#!/usr/bin/env python3
"""Turn the research tables + simplified GeoJSON into geo.js and data-map.js for the page.

Run from berlin-rent/:  python3 -I build/make_data.py
Inputs: build/*.json (mapshaper output), research/raw/*.json (IBB + Zensus tables).
Nothing is interpolated: missing values stay null.
"""
import json, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
B, R = ROOT / 'build', ROOT / 'research' / 'raw'
YEARS = list(range(2012, 2026))


def load(p):
    return json.loads(pathlib.Path(p).read_text())


def ring_area_centroid(ring):
    a = cx = cy = 0.0
    for (x1, y1), (x2, y2) in zip(ring, ring[1:]):
        c = x1 * y2 - x2 * y1
        a += c; cx += (x1 + x2) * c; cy += (y1 + y2) * c
    if abs(a) < 1e-12:
        return 0, ring[0][0], ring[0][1]
    return a / 2, cx / (3 * a), cy / (3 * a)


def centroid(geom):
    polys = geom['coordinates'] if geom['type'] == 'MultiPolygon' else [geom['coordinates']]
    best = max((ring_area_centroid(p[0]) for p in polys), key=lambda t: abs(t[0]))
    return best[1], best[2]


def inside(pt, ring):
    x, y = pt; c = False
    for (x1, y1), (x2, y2) in zip(ring, ring[1:]):
        if (y1 > y) != (y2 > y) and x < (x2 - x1) * (y - y1) / (y2 - y1) + x1:
            c = not c
    return c


plr = load(B / 'plr.json')
_r = load(B / 'ring.json')
ring_geom = _r['geometries'][0] if _r['type'] == 'GeometryCollection' else _r['features'][0]['geometry']
ring_outer = (ring_geom['coordinates'][0] if ring_geom['type'] == 'Polygon' else ring_geom['coordinates'][0][0])
ask = load(R / 'asking_rent_plr_ibb_2012_2025.json')['data']
zen = load(R / 'existing_rent_zensus2022_by_bezirk_and_plr.json')

areas = {}
for f in plr['features']:
    p = f['properties']; i = p['PLR_ID']
    cx, cy = centroid(f['geometry'])
    med, mean, n = [], [], []
    for y in YEARS:
        v = ask.get(str(y), {}).get(i)
        med.append(v.get('median') if v else None)
        mean.append(v.get('mean') if v else None)
        n.append(v.get('n') if v else None)
    z = zen['planungsraeume'].get(i) or {}
    areas[i] = {
        'name': p['PLR_NAME'], 'bez': p['BEZ'], 'ring': inside((cx, cy), ring_outer),
        'c': [round(cx, 4), round(cy, 4)], 'med': med, 'mean': mean, 'n': n,
        'ex': z.get('rent_mean_eur_m2'), 'exN': z.get('rented_dwellings_in_cells'),
    }
    f['properties'] = {'id': i}


def to_fc(g):  # mapshaper writes a bare GeometryCollection when dissolving without fields
    if g.get('type') == 'GeometryCollection':
        return {'type': 'FeatureCollection', 'features': [{'type': 'Feature', 'properties': {}, 'geometry': x} for x in g['geometries']]}
    return g


geo = {k: to_fc(load(B / f'{k}.json')) for k in ['bez', 'border', 'lines', 'thf', 'ring']}
geo['plr'] = plr
for f in geo['bez']['features']:
    f['properties'] = {'bez': f['properties']['BEZ']}

(ROOT / 'geo.js').write_text(
    '// Simplified boundaries (WGS84). Generated by build/make_data.py, do not edit by hand.\n'
    '// LOR Planungsräume 2021: Amt für Statistik Berlin-Brandenburg via ODIS, CC BY 3.0 DE.\n'
    '// U/S-Bahn lines: VBB GTFS shapes (March 2026). Tempelhofer Feld: OpenStreetMap (ODbL).\n'
    'const GEO = ' + json.dumps(geo, separators=(',', ':'), ensure_ascii=False) + ';\n')
(ROOT / 'data-map.js').write_text(
    '// Rent values per LOR Planungsraum. Generated by build/make_data.py from research/raw.\n'
    '// med/mean/n: IBB asking rents (Angebotsmieten, € net cold per m², listings) for YEARS; null = no data.\n'
    '// ex: Zensus 2022 mean existing net cold rent per m², aggregated by us from the 100 m grid.\n'
    'const MAPDATA = ' + json.dumps({'years': YEARS, 'areas': areas}, separators=(',', ':'), ensure_ascii=False) + ';\n')

# quick stats for copy
def stat(y, thr):
    k = YEARS.index(y); out = [a for a in areas.values() if not a['ring'] and a['med'][k] is not None]
    return sum(1 for a in out if a['med'][k] >= thr), len(out)
for thr in (10, 12):
    print('outside ring >=', thr, {y: stat(y, thr) for y in (2012, 2015, 2019, 2022, 2025)})
print('inside ring count', sum(a['ring'] for a in areas.values()))
